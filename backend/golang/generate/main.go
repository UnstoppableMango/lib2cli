// Command generate writes commands.go for a generated Go shim. lib2cli
// copies it into the project beside the runtime, and main.go runs it with
// go generate before the build.
//
// It reads the plan from lib2cli.json, loads the library's exported types
// from the compiler's export data, and writes for each command a call
// that converts the runtime's neutral values to the function's own
// parameter types, injects a leading context.Context, returns a trailing
// error, and writes the result. A signature the model does not fit fails
// here, before anything is built. It uses only the standard library and
// the go command.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	"go/importer"
	"go/parser"
	"go/token"
	"go/types"
	"io"
	"os"
	"os/exec"
	"reflect"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

// header marks the generated file.
const header = "// Code generated by lib2cli. DO NOT EDIT.\n\n"

// plan is the part of lib2cli's plan the generator reads.
type plan struct {
	Package  string    `json:"package"`
	Commands []command `json:"commands"`
}

type command struct {
	Name   string  `json:"name"`
	Func   string  `json:"func"`
	Whole  bool    `json:"whole"`
	Params []param `json:"params"`
	Result typ     `json:"result"`
}

type param struct {
	Name string `json:"name"`
	Flag string `json:"flag"`
	Type typ    `json:"type"`
}

type typ struct {
	Kind string `json:"kind"`
	Elem *typ   `json:"elem,omitempty"`
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintf(os.Stderr, "lib2cli: %v\n", err)
		os.Exit(1)
	}
}

func run() error {
	data, err := os.ReadFile("lib2cli.json")
	if err != nil {
		return err
	}
	var p plan
	if err := json.Unmarshal(data, &p); err != nil {
		return fmt.Errorf("lib2cli.json: %w", err)
	}
	taken, err := declared("shim.go", "main.go")
	if err != nil {
		return err
	}
	pkgs, err := load(p.Package, "io")
	if err != nil {
		return err
	}
	src, err := generate(&p, pkgs[0], pkgs[1], taken)
	if err != nil {
		return err
	}
	return os.WriteFile("commands.go", src, 0o644)
}

// declared is the names Go files declare at package level, which an import
// name in commands.go must not reuse.
func declared(files ...string) (map[string]bool, error) {
	names := map[string]bool{}
	for _, file := range files {
		f, err := parser.ParseFile(token.NewFileSet(), file, nil, 0)
		if err != nil {
			return nil, err
		}
		addDecls(names, f)
	}
	return names, nil
}

func addDecls(names map[string]bool, f *ast.File) {
	for _, d := range f.Decls {
		switch d := d.(type) {
		case *ast.FuncDecl:
			if d.Recv == nil {
				names[d.Name.Name] = true
			}
		case *ast.GenDecl:
			for _, s := range d.Specs {
				switch s := s.(type) {
				case *ast.TypeSpec:
					names[s.Name.Name] = true
				case *ast.ValueSpec:
					for _, n := range s.Names {
						names[n.Name] = true
					}
				}
			}
		}
	}
}

// load type-checks nothing itself: it asks the go command for each
// package's export data, building the packages as the shim's build would,
// and reads their types from it.
func load(paths ...string) ([]*types.Package, error) {
	args := append([]string{"list", "-export", "-deps", "-json=ImportPath,Export"}, paths...)
	cmd := exec.Command("go", args...)
	cmd.Stderr = os.Stderr
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go list: %w", err)
	}
	exports := map[string]string{}
	dec := json.NewDecoder(bytes.NewReader(out))
	for dec.More() {
		var p struct{ ImportPath, Export string }
		if err := dec.Decode(&p); err != nil {
			return nil, fmt.Errorf("go list: %w", err)
		}
		exports[p.ImportPath] = p.Export
	}

	imp := importer.ForCompiler(token.NewFileSet(), "gc", func(path string) (io.ReadCloser, error) {
		file := exports[path]
		if file == "" {
			return nil, fmt.Errorf("go list has no export data for %s", path)
		}
		return os.Open(file)
	})
	pkgs := make([]*types.Package, len(paths))
	for i, path := range paths {
		if pkgs[i], err = imp.Import(path); err != nil {
			return nil, err
		}
	}
	return pkgs, nil
}

// generate writes commands.go. taken holds the package-level names the
// rest of package main declares.
func generate(p *plan, lib, ioPkg *types.Package, taken map[string]bool) ([]byte, error) {
	g := &gen{
		lib:     lib,
		reader:  ioPkg.Scope().Lookup("Reader").Type(),
		imports: map[string]string{"context": "context", "io": "io", lib.Path(): "lib"},
		names:   map[string]string{"context": "context", "io": "io", lib.Path(): lib.Name()},
		used:    map[string]bool{},
		taken:   map[string]bool{"context": true, "io": true, "lib": true, "commands": true},
	}
	for n := range taken {
		g.taken[n] = true
	}

	var body strings.Builder
	var errs []error
	for _, c := range p.Commands {
		entry, err := g.command(c)
		if err != nil {
			errs = append(errs, fmt.Errorf("command %s: %w", c.Name, err))
			continue
		}
		body.WriteString(entry)
	}
	if len(errs) > 0 {
		return nil, errors.Join(errs...)
	}

	var b strings.Builder
	b.WriteString(header)
	b.WriteString("package main\n\n")
	paths := make([]string, 0, len(g.used))
	for path := range g.used {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	if len(paths) > 0 {
		b.WriteString("import (\n")
		for _, path := range paths {
			if name := g.imports[path]; name != g.names[path] {
				fmt.Fprintf(&b, "%s %q\n", name, path)
			} else {
				fmt.Fprintf(&b, "%q\n", path)
			}
		}
		b.WriteString(")\n\n")
	}
	fmt.Fprintf(&b, "var commands = []command{\n%s}\n", body.String())

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		// Every expression comes from a quoted string, a checked name or
		// go/types, so this is a bug in the generator.
		return nil, fmt.Errorf("generated commands.go does not parse: %w\n%s", err, b.String())
	}
	return src, nil
}

// gen holds what one commands.go needs across its commands.
type gen struct {
	lib    *types.Package
	reader types.Type // io.Reader

	imports map[string]string // import path to the name commands.go uses
	names   map[string]string // import path to the package's own name
	used    map[string]bool   // import paths commands.go refers to
	taken   map[string]bool   // names an import may not use

	// Per command: the next fresh variable, and whether a conversion
	// needs err declared.
	n       int
	needErr bool
}

// locals are the names a call declares, which no import may shadow.
var locals = regexp.MustCompile(`^(ctx|args|out|err|req|res|v[0-9]+)$`)

// qualify names a package in commands.go, importing it on first use.
func (g *gen) qualify(p *types.Package) string {
	g.used[p.Path()] = true
	if name, ok := g.imports[p.Path()]; ok {
		return name
	}
	g.names[p.Path()] = p.Name()
	name := p.Name()
	for i := 2; g.taken[name] || locals.MatchString(name); i++ {
		name = p.Name() + "pkg" + strconv.Itoa(i)
	}
	g.taken[name] = true
	g.imports[p.Path()] = name
	return name
}

// typeString writes t as commands.go refers to it.
func (g *gen) typeString(t types.Type) string {
	return types.TypeString(t, g.qualify)
}

// fresh names a new variable.
func (g *gen) fresh() string {
	g.n++
	return "v" + strconv.Itoa(g.n)
}

// command writes one command's table entry.
func (g *gen) command(c command) (string, error) {
	g.n, g.needErr = 0, false

	fn, ok := g.lib.Scope().Lookup(c.Func).(*types.Func)
	if !ok {
		return "", fmt.Errorf("%s has no function %s", g.lib.Path(), c.Func)
	}
	sig := fn.Type().(*types.Signature)
	if sig.Variadic() {
		return "", fmt.Errorf("%s is variadic, which a command cannot call", c.Func)
	}

	ins := sig.Params()
	first := 0
	var args []string
	if ins.Len() > 0 && isNamed(ins.At(0).Type(), "context", "Context") {
		first = 1
		args = append(args, "ctx")
	}
	want := len(c.Params)
	if c.Whole {
		want = 1
	}
	if ins.Len()-first != want {
		return "", fmt.Errorf("%s takes %d argument(s), but the model gives it %d", c.Func, ins.Len()-first, want)
	}

	outs := sig.Results()
	n := outs.Len()
	fails := n > 0 && types.Identical(outs.At(n-1).Type(), types.Universe.Lookup("error").Type())
	if fails {
		n--
	}
	if n > 1 {
		return "", fmt.Errorf("%s returns %d values; a command writes one", c.Func, n)
	}

	var body strings.Builder
	if c.Whole {
		t := ins.At(first).Type()
		st, elem := structOf(t)
		if st == nil {
			return "", fmt.Errorf("%s takes %s, but a whole command passes a struct", c.Func, t)
		}
		if elem != nil {
			fmt.Fprintf(&body, "req := new(%s)\n", g.typeString(elem))
		} else {
			fmt.Fprintf(&body, "var req %s\n", g.typeString(t))
		}
		for i, p := range c.Params {
			f := field(st, p.Name)
			if f == nil {
				return "", fmt.Errorf("%s has no exported field for %s", t, p.Name)
			}
			if err := g.convert(&body, "req."+f.Name(), fmt.Sprintf("args[%d]", i), p.Type, f.Type(), i); err != nil {
				return "", fmt.Errorf("%s: %w", p.Name, err)
			}
		}
		args = append(args, "req")
	} else {
		for i, p := range c.Params {
			v := g.fresh()
			if err := g.declare(&body, v, fmt.Sprintf("args[%d]", i), p.Type, ins.At(first+i).Type(), i); err != nil {
				return "", fmt.Errorf("%s: %w", p.Name, err)
			}
			args = append(args, v)
		}
	}

	call := fmt.Sprintf("lib.%s(%s)", fn.Name(), strings.Join(args, ", "))
	g.used[g.lib.Path()] = true
	switch {
	case n == 0 && fails:
		fmt.Fprintf(&body, "return %s\n", call)
	case n == 0:
		fmt.Fprintf(&body, "%s\nreturn nil\n", call)
	default:
		if fails {
			fmt.Fprintf(&body, "res, err := %s\nif err != nil {\nreturn err\n}\n", call)
		} else {
			fmt.Fprintf(&body, "res := %s\n", call)
		}
		w, err := g.write(c.Result, outs.At(0).Type(), "res")
		if err != nil {
			return "", fmt.Errorf("result: %w", err)
		}
		body.WriteString(w)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "{\nname: %q,\n", c.Name)
	if len(c.Params) > 0 {
		b.WriteString("params: []param{\n")
		for _, p := range c.Params {
			fmt.Fprintf(&b, "{name: %q, flag: %q, typ: %s},\n", p.Name, p.Flag, typLiteral(p.Type))
		}
		b.WriteString("},\n")
	}
	b.WriteString("call: func(ctx context.Context, args []any, out io.Writer) error {\n")
	g.used["context"], g.used["io"] = true, true
	if g.needErr {
		b.WriteString("var err error\n")
	}
	fmt.Fprintf(&b, "%s},\n},\n", body.String())
	return b.String(), nil
}

// declare writes statements declaring v, of type t, from src, as convert
// does.
func (g *gen) declare(b *strings.Builder, v, src string, nt typ, t types.Type, i int) error {
	if e, ok := g.expr(src, nt, t); ok {
		fmt.Fprintf(b, "%s := %s\n", v, e)
		return nil
	}
	fmt.Fprintf(b, "var %s %s\n", v, g.typeString(t))
	return g.convert(b, v, src, nt, t, i)
}

// expr is the expression of type t that converts src, when one cannot
// fail.
func (g *gen) expr(src string, nt typ, t types.Type) (string, bool) {
	u := t.Underlying()
	switch {
	case (nt.Kind == "string" || nt.Kind == "path" || nt.Kind == "text") && isBasic(u, types.IsString):
		return g.conversion(t, src+".(string)", types.Typ[types.String]), true
	case nt.Kind == "float" && isBasic(u, types.IsFloat):
		return g.conversion(t, src+".(float64)", types.Typ[types.Float64]), true
	case nt.Kind == "bool" && isBasic(u, types.IsBoolean):
		return g.conversion(t, src+".(bool)", types.Typ[types.Bool]), true
	case nt.Kind == "bytes" && isBytes(u):
		return g.conversion(t, src+".([]byte)", types.NewSlice(types.Typ[types.Byte])), true
	case nt.Kind == "stream" && types.Identical(t, g.reader):
		return src + ".(io.Reader)", true
	}
	return "", false
}

// convert writes statements setting dst, of type t, from src, a neutral
// value of type nt. A value that does not convert returns an argError for
// parameter i.
func (g *gen) convert(b *strings.Builder, dst, src string, nt typ, t types.Type, i int) error {
	u := t.Underlying()
	mismatch := fmt.Errorf("the model gives a %s, but the function takes %s", describe(nt), t)
	if e, ok := g.expr(src, nt, t); ok {
		fmt.Fprintf(b, "%s = %s\n", dst, e)
		return nil
	}
	// assign assigns a scalar to a type, such as any, that holds it as it
	// is.
	assign := func(from string, ft types.Type) error {
		if !types.AssignableTo(ft, t) {
			return mismatch
		}
		fmt.Fprintf(b, "%s = %s.(%s)\n", dst, src, from)
		return nil
	}
	fallible := func(expr string) {
		g.needErr = true
		fmt.Fprintf(b, "if %s, err = %s; err != nil {\nreturn argError{%d, err}\n}\n", dst, expr, i)
	}

	switch nt.Kind {
	case "string", "path", "text":
		return assign("string", types.Typ[types.String])
	case "float":
		return assign("float64", types.Typ[types.Float64])
	case "bool":
		return assign("bool", types.Typ[types.Bool])
	case "bytes":
		return assign("[]byte", types.NewSlice(types.Typ[types.Byte]))
	case "int":
		if !isBasic(u, types.IsInteger) {
			return assign("int64", types.Typ[types.Int64])
		}
		fallible(fmt.Sprintf("integer[%s](%s)", g.typeString(t), src))
	case "stream":
		switch {
		case types.AssignableTo(g.reader, t):
			fmt.Fprintf(b, "%s = %s.(io.Reader)\n", dst, src)
		case isBasic(u, types.IsString) || isBytes(u):
			fallible(fmt.Sprintf("readAll[%s](%s)", g.typeString(t), src))
		default:
			return mismatch
		}
	case "object":
		g.needErr = true
		fmt.Fprintf(b, "if err = decode(%s, &%s); err != nil {\nreturn argError{%d, err}\n}\n", src, dst, i)
	case "option":
		fmt.Fprintf(b, "if %s != nil {\n", src)
		if p, ok := u.(*types.Pointer); ok {
			v := g.fresh()
			if err := g.declare(b, v, src, *nt.Elem, p.Elem(), i); err != nil {
				return err
			}
			fmt.Fprintf(b, "%s = &%s\n", dst, v)
		} else if err := g.convert(b, dst, src, *nt.Elem, t, i); err != nil {
			return err
		}
		b.WriteString("}\n")
	case "list":
		s, ok := u.(*types.Slice)
		if !ok {
			return mismatch
		}
		l, k, e := g.fresh(), g.fresh(), g.fresh()
		fmt.Fprintf(b, "if %s != nil {\n%s := %s.([]any)\n%s = make(%s, len(%s))\nfor %s, %s := range %s {\n", src, l, src, dst, g.typeString(t), l, k, e, l)
		if err := g.convert(b, dst+"["+k+"]", e, *nt.Elem, s.Elem(), i); err != nil {
			return err
		}
		b.WriteString("}\n}\n")
	case "map":
		m, ok := u.(*types.Map)
		if !ok || !isBasic(m.Key().Underlying(), types.IsString) {
			return mismatch
		}
		mv, k, e, v := g.fresh(), g.fresh(), g.fresh(), g.fresh()
		fmt.Fprintf(b, "if %s != nil {\n%s := %s.(map[string]any)\n%s = make(%s, len(%s))\nfor %s, %s := range %s {\n", src, mv, src, dst, g.typeString(t), mv, k, e, mv)
		if err := g.declare(b, v, e, *nt.Elem, m.Elem(), i); err != nil {
			return err
		}
		fmt.Fprintf(b, "%s[%s] = %s\n}\n}\n", dst, g.conversion(m.Key(), k, types.Typ[types.String]), v)
	default:
		return fmt.Errorf("unknown kind %q", nt.Kind)
	}
	return nil
}

// write writes statements writing v, of type t, as a result of type nt.
func (g *gen) write(nt typ, t types.Type, v string) (string, error) {
	u := t.Underlying()
	mismatch := fmt.Errorf("the model writes a %s, but the function returns %s", describe(nt), t)
	str := func() string {
		return fmt.Sprintf("return writeString(out, %s)\n", g.conversion(types.Typ[types.String], v, t))
	}
	stringer := func() string { return fmt.Sprintf("return writeString(out, %s.String())\n", v) }

	switch nt.Kind {
	case "string", "path":
		switch {
		case isBasic(u, types.IsString):
			return str(), nil
		case isStringer(t):
			return stringer(), nil
		}
	case "text":
		switch {
		case isStringer(t):
			return stringer(), nil
		case isBasic(u, types.IsString):
			return str(), nil
		}
	case "bytes":
		if isBytes(u) {
			return fmt.Sprintf("return writeBytes(out, %s)\n", g.conversion(types.NewSlice(types.Typ[types.Byte]), v, t)), nil
		}
	case "stream":
		switch {
		case types.AssignableTo(t, g.reader):
			return fmt.Sprintf("return writeStream(out, %s)\n", v), nil
		case isBasic(u, types.IsString):
			return str(), nil
		case isBytes(u):
			return fmt.Sprintf("return writeBytes(out, %s)\n", g.conversion(types.NewSlice(types.Typ[types.Byte]), v, t)), nil
		}
	case "int":
		if isBasic(u, types.IsInteger) {
			return fmt.Sprintf("return writeJSON(out, %s)\n", v), nil
		}
	case "float":
		if isBasic(u, types.IsFloat) {
			return fmt.Sprintf("return writeJSON(out, %s)\n", v), nil
		}
	case "bool":
		if isBasic(u, types.IsBoolean) {
			return fmt.Sprintf("return writeJSON(out, %s)\n", v), nil
		}
	case "list", "map", "object":
		return fmt.Sprintf("return writeJSON(out, %s)\n", v), nil
	case "option":
		// A nil option writes nothing where the result is raw, and null
		// where it is JSON.
		none := "writeJSON(out, nil)"
		switch nt.Elem.Kind {
		case "string", "path", "text", "bytes", "stream":
			none = "nil"
		}
		if !nilable(u) {
			return g.write(*nt.Elem, t, v)
		}
		var rest string
		var err error
		if p, ok := u.(*types.Pointer); ok && !(nt.Elem.Kind == "text" && isStringer(t) && !isStringer(p.Elem())) {
			// Write what the pointer points to, unless only the pointer
			// has the String method text calls.
			e := g.fresh()
			if rest, err = g.write(*nt.Elem, p.Elem(), e); err == nil {
				rest = fmt.Sprintf("%s := *%s\n%s", e, v, rest)
			}
		} else {
			rest, err = g.write(*nt.Elem, t, v)
		}
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("if %s == nil {\nreturn %s\n}\n%s", v, none, rest), nil
	default:
		return "", fmt.Errorf("unknown kind %q", nt.Kind)
	}
	return "", mismatch
}

// conversion converts expr, of type from, to t, writing nothing when the
// types are already identical.
func (g *gen) conversion(t types.Type, expr string, from types.Type) string {
	if types.Identical(t, from) {
		return expr
	}
	return g.typeString(t) + "(" + expr + ")"
}

// structOf is the struct a whole command builds for t: t's own, or the
// one t points to, with the pointed-to type as elem.
func structOf(t types.Type) (st *types.Struct, elem types.Type) {
	if p, ok := t.Underlying().(*types.Pointer); ok {
		st, _ := p.Elem().Underlying().(*types.Struct)
		return st, p.Elem()
	}
	st, _ = t.Underlying().(*types.Struct)
	return st, nil
}

// field finds the exported field of st that name sets: the one whose json
// tag is name or, without a tag, whose name matches it ignoring case and
// underscores.
func field(st *types.Struct, name string) *types.Var {
	norm := func(s string) string { return strings.ToLower(strings.ReplaceAll(s, "_", "")) }
	for i := 0; i < st.NumFields(); i++ {
		f := st.Field(i)
		if !f.Exported() {
			continue
		}
		tag, _, _ := strings.Cut(reflect.StructTag(st.Tag(i)).Get("json"), ",")
		if tag == name || (tag == "" && norm(f.Name()) == norm(name)) {
			return f
		}
	}
	return nil
}

func isNamed(t types.Type, pkg, name string) bool {
	n, ok := t.(*types.Named)
	return ok && n.Obj().Pkg() != nil && n.Obj().Pkg().Path() == pkg && n.Obj().Name() == name
}

func isBasic(u types.Type, info types.BasicInfo) bool {
	b, ok := u.(*types.Basic)
	return ok && b.Info()&info != 0
}

func isBytes(u types.Type) bool {
	s, ok := u.(*types.Slice)
	if !ok {
		return false
	}
	b, ok := s.Elem().Underlying().(*types.Basic)
	return ok && b.Kind() == types.Byte
}

func nilable(u types.Type) bool {
	switch u.(type) {
	case *types.Pointer, *types.Interface, *types.Slice, *types.Map, *types.Chan, *types.Signature:
		return true
	}
	return false
}

// stringerType is fmt.Stringer.
var stringerType = types.NewInterfaceType([]*types.Func{
	types.NewFunc(token.NoPos, nil, "String", types.NewSignatureType(nil, nil, nil, nil,
		types.NewTuple(types.NewVar(token.NoPos, nil, "", types.Typ[types.String])), false)),
}, nil).Complete()

func isStringer(t types.Type) bool { return types.Implements(t, stringerType) }

// describe names a neutral type in an error.
func describe(t typ) string {
	if t.Elem != nil {
		return t.Kind + " of " + describe(*t.Elem)
	}
	return t.Kind
}

// typLiteral writes a neutral type as the runtime's typ literal.
func typLiteral(t typ) string {
	if t.Elem == nil {
		return fmt.Sprintf("typ{kind: %q}", t.Kind)
	}
	return fmt.Sprintf("typ{kind: %q, elem: &%s}", t.Kind, typLiteral(*t.Elem))
}
