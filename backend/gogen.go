package backend

import (
	"encoding/json"
	"fmt"
	"go/token"
	"strings"
	"unicode"
	"unicode/utf8"

	"github.com/unstoppablemango/lib2cli/backend/golang"
	"github.com/unstoppablemango/tdl/plugin"
	"golang.org/x/mod/module"
)

// goVersion is the go directive of a generated go.mod: the oldest Go the
// shim runtime builds with.
const goVersion = "1.22"

// header marks every generated Go file.
const header = "// Code generated by lib2cli. DO NOT EDIT.\n\n"

// goFiles writes the Go project for a plan bound to a Go module: go.mod
// pinning the library, lib2cli.json holding the plan, main.go, shim.go, the
// runtime that parses flags, and generate.go. The library's source is not
// here when tdl runs, so go generate runs generate.go at build time to
// read the library's real signatures and write commands.go, a purpose-built
// call for each command.
func goFiles(p *Plan) ([]*plugin.File, []*plugin.Diagnostic) {
	var diags []*plugin.Diagnostic
	errorf := func(format string, args ...any) {
		diags = append(diags, &plugin.Diagnostic{
			Severity: plugin.Severity_SEVERITY_ERROR,
			Message:  fmt.Sprintf(format, args...),
		})
	}

	// go.mod is written from these, so a bad one would only surface when
	// the project fails to build.
	if err := module.Check(p.Package, p.Version); err != nil {
		errorf("go(%q, %q) is not a Go module version: %v", p.Package, p.Version, err)
	}
	if strings.Contains(p.Bin, "/") || module.CheckImportPath(p.Bin) != nil {
		errorf("%q cannot name a Go binary: name it with bin(\"name\")", p.Bin)
	}

	for _, c := range p.Commands {
		if fn := goFunc(c.Func); !token.IsIdentifier(fn) || !token.IsExported(fn) {
			errorf("%s is not an exported Go function name: name the function with func(\"Name\")", c.Func)
		}
	}
	if len(diags) > 0 {
		return nil, diags
	}

	// The generator reads the plan with each function's Go name.
	gp := *p
	gp.Commands = make([]Command, len(p.Commands))
	for i, c := range p.Commands {
		c.Func = goFunc(c.Func)
		gp.Commands[i] = c
	}
	planJSON, err := json.MarshalIndent(gp, "", "  ")
	if err != nil {
		// A Plan holds only strings, bools and slices of them.
		panic(err)
	}

	main := header + "package main\n\n" +
		"//go:generate go run generate.go\n\n" +
		fmt.Sprintf("func main() { run(%q, commands) }\n", p.Bin)
	mod := fmt.Sprintf("module %s\n\ngo %s\n\nrequire %s %s\n", p.Bin, goVersion, p.Package, p.Version)
	return []*plugin.File{
		{Path: "go.mod", Content: []byte(mod)},
		{Path: "lib2cli.json", Content: append(planJSON, '\n')},
		{Path: "main.go", Content: []byte(main)},
		{Path: "shim.go", Content: []byte(shimSource())},
		{Path: "generate.go", Content: []byte(generateSource())},
	}, nil
}

// goFunc is a function's Go name: a name from the model with its first
// letter upper-cased, so convertFile calls ConvertFile.
func goFunc(name string) string {
	r, n := utf8.DecodeRuneInString(name)
	return string(unicode.ToUpper(r)) + name[n:]
}

// shimSource is the runtime as package main, without its package
// documentation.
func shimSource() string {
	const clause = "\npackage shim\n"
	return header + "package main\n" + golang.Shim[strings.Index(golang.Shim, clause)+len(clause):]
}

// generateSource is the generator, kept out of the shim's build by its
// build constraint.
func generateSource() string {
	return "//go:build ignore\n\n" + header + golang.Generate
}
