package backend

import (
	"fmt"
	gofmt "go/format"
	"go/token"
	"strconv"
	"strings"
	"unicode"
	"unicode/utf8"

	"github.com/unstoppablemango/lib2cli/backend/golang/shim"
	"github.com/unstoppablemango/tdl/plugin"
	"golang.org/x/mod/module"
)

// goVersion is the go directive of a generated go.mod: the oldest Go the
// shim runtime builds with.
const goVersion = "1.22"

// header marks every generated Go file.
const header = "// Code generated by lib2cli. DO NOT EDIT.\n\n"

// goFiles writes a buildable Go project for a plan bound to a Go module:
// go.mod pinning the library, main.go with the command table, and shim.go,
// the runtime that parses flags and calls each function.
func goFiles(p *Plan) ([]*plugin.File, []*plugin.Diagnostic) {
	var diags []*plugin.Diagnostic
	errorf := func(format string, args ...any) {
		diags = append(diags, &plugin.Diagnostic{
			Severity: plugin.Severity_SEVERITY_ERROR,
			Message:  fmt.Sprintf(format, args...),
		})
	}

	// go.mod is written from these, so a bad one would only surface when
	// the project fails to build.
	if err := module.Check(p.Package, p.Version); err != nil {
		errorf("go(%q, %q) is not a Go module version: %v", p.Package, p.Version, err)
	}
	if strings.Contains(p.Bin, "/") || module.CheckImportPath(p.Bin) != nil {
		errorf("%q cannot name a Go binary: name it with bin(\"name\")", p.Bin)
	}

	var b strings.Builder
	b.WriteString(header)
	b.WriteString("package main\n\n")
	fmt.Fprintf(&b, "import lib %q\n\n", p.Package)
	b.WriteString("var commands = []command{\n")
	for _, c := range p.Commands {
		fn := goFunc(c.Func)
		if !token.IsIdentifier(fn) || !token.IsExported(fn) {
			errorf("%s is not an exported Go function name: name the function with func(\"Name\")", c.Func)
			continue
		}
		fmt.Fprintf(&b, "{\nname: %q,\nfn: lib.%s,\n", c.Name, fn)
		if c.Whole {
			b.WriteString("whole: true,\n")
		}
		if len(c.Params) > 0 {
			b.WriteString("params: []param{\n")
			for _, prm := range c.Params {
				fmt.Fprintf(&b, "{name: %q, flag: %q, typ: %s},\n", prm.Name, prm.Flag, goTyp(prm.Type))
			}
			b.WriteString("},\n")
		}
		fmt.Fprintf(&b, "result: %s,\n},\n", goTyp(c.Result))
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "func main() { run(%q, commands) }\n", p.Bin)
	if len(diags) > 0 {
		return nil, diags
	}

	main, err := gofmt.Source([]byte(b.String()))
	if err != nil {
		// The source is built from quoted strings and checked names, so
		// this is a bug in the generator.
		panic(fmt.Sprintf("generated main.go does not parse: %v\n%s", err, b.String()))
	}

	mod := fmt.Sprintf("module %s\n\ngo %s\n\nrequire %s %s\n", p.Bin, goVersion, p.Package, p.Version)
	return []*plugin.File{
		{Path: "go.mod", Content: []byte(mod)},
		{Path: "main.go", Content: main},
		{Path: "shim.go", Content: []byte(shimSource())},
	}, nil
}

// goFunc is a function's Go name: a name from the model with its first
// letter upper-cased, so convertFile calls ConvertFile.
func goFunc(name string) string {
	r, n := utf8.DecodeRuneInString(name)
	return string(unicode.ToUpper(r)) + name[n:]
}

// goTyp writes a type as a typ literal.
func goTyp(t Type) string {
	if t.Elem == nil {
		return fmt.Sprintf("typ{kind: %s}", strconv.Quote(string(t.Kind)))
	}
	return fmt.Sprintf("typ{kind: %s, elem: &%s}", strconv.Quote(string(t.Kind)), goTyp(*t.Elem))
}

// shimSource is the runtime as package main, without its package
// documentation.
func shimSource() string {
	src := shim.Source
	i := strings.Index(src, "\npackage shim\n")
	return header + "package main\n" + src[i+len("\npackage shim\n"):]
}
